def context_budget(model: str = "") -> tuple:
    """Окно говорящей модели: (сколько всего токенов, запас на ответ).

    Одним числом мерить нельзя: местные модели живут в окне Ollama
    (OPTIONS), а облачным оно мало, поэтому у них своё — CLOUD_NUM_CTX.
    Иначе облачный участник забывал бы начало сцены по олламовской мерке
    в 7 тысяч токенов, хотя шлюз принял бы в разы больше.

    Запас на ответ у обоих — предел длины реплики: у местных это
    OPTIONS["num_predict"], у облачных — CLOUD_MAX_TOKENS, если он задан
    (иначе тот же num_predict, как было). Исключение — окно, которое меньше
    самого запаса: так бывает при опечатке в настройке, и расплачиваться за неё
    история не должна, иначе участник останется без неё вовсе.
    """
    if str(model or "").startswith(CLOUD_MODEL_PREFIX):
        window = int(CLOUD_NUM_CTX)
        if window <= 0:                      # 0 — окно не ограничено
            return 0, 0
        # Но и запас не должен съедать само окно: у вендора с четырьмя тысячами
        # токенов ответ там не 8192, а история всё равно должна остаться.
        # Поэтому ответу — не больше половины того, что осталось после
        # обязательного запаса (при обычном окне это всё тот же предел ответа)
        reserve = int(CLOUD_MAX_TOKENS or 0) or int(OPTIONS.get("num_predict", 0) or 0)
        return window, min(reserve, max(0, window - CONTEXT_SAFETY_MARGIN) // 2)
    return int(OPTIONS["num_ctx"]), int(OPTIONS["num_predict"])
